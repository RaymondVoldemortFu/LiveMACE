from dataclasses import dataclass, field
from datetime import datetime
from decimal import Decimal
from typing import List, Dict, Optional, Any
from sqlalchemy.orm import Session
from sqlalchemy import select, and_, func

from backend.database.models import Trade, CryptoKline, CryptoPrice

@dataclass
class CloseRecord:
    trade_id: int
    time: datetime
    price: Decimal
    matched_qty: Decimal
    fee: Decimal

@dataclass
class ExposureLot:
    """
    Exposure Lot (Tracking Unit)
    Generated by a single BUY Trade.
    """
    lot_id: str  # Unique identifier (e.g., "lot_{trade_id}")
    account_id: int
    symbol: str
    
    # Open info
    open_trade_id: int
    open_time: datetime
    open_price: Decimal
    open_quantity: Decimal
    open_fee: Decimal
    open_interest: Decimal # Interest charged at open (or accumulated)
    
    # State
    remaining_quantity: Decimal
    close_records: List[CloseRecord] = field(default_factory=list)
    
    # Evaluation results (populated at the end)
    close_value: Decimal = Decimal(0)
    unrealized_value: Decimal = Decimal(0)
    unrealized_pnl: Decimal = Decimal(0)
    total_pnl: Decimal = Decimal(0)
    holding_period: Optional[float] = None # Seconds
    
    def add_close_record(self, record: CloseRecord):
        self.close_records.append(record)
        self.remaining_quantity -= record.matched_qty
        
    def calculate_metrics(self, mark_price: Optional[Decimal] = None, end_time: Optional[datetime] = None):
        """
        Calculate PnL and other metrics.
        
        open_cost = open_price * open_qty + open_fee + interest
        close_value = Σ(close_price * close_qty − close_fee)
        unrealized = remaining_qty * mark_price
        pnl = close_value + unrealized − open_cost
        """
        self.open_cost = (self.open_price * self.open_quantity) + self.open_fee + self.open_interest
        
        self.close_value = sum(
            (r.price * r.matched_qty) - r.fee 
            for r in self.close_records
        )
        
        if self.remaining_quantity > 0:
            if mark_price is None:
                # If no mark price, we can't calculate unrealized PnL accurately.
                # Assuming 0 or keeping it separate.
                self.unrealized_value = Decimal(0)
            else:
                self.unrealized_value = self.remaining_quantity * mark_price
                
        self.total_pnl = self.close_value + self.unrealized_value - self.open_cost
        
        # Calculate holding period (weighted average or time to full close?)
        # For simplicity, time from open to last close or end_time
        last_time = self.open_time
        if self.close_records:
            last_time = max(r.time for r in self.close_records)
        if end_time and end_time > last_time:
            last_time = end_time
            
        self.holding_period = (last_time - self.open_time).total_seconds()

    def to_dict(self) -> Dict[str, Any]:
        return {
            "lot_id": self.lot_id,
            "account_id": self.account_id,
            "symbol": self.symbol,
            "open_trade_id": self.open_trade_id,
            "open_time": self.open_time.isoformat(),
            "open_price": float(self.open_price),
            "open_quantity": float(self.open_quantity),
            "open_fee": float(self.open_fee),
            "open_interest": float(self.open_interest),
            "remaining_quantity": float(self.remaining_quantity),
            "close_records": [
                {
                    "trade_id": r.trade_id,
                    "time": r.time.isoformat(),
                    "price": float(r.price),
                    "matched_qty": float(r.matched_qty),
                    "fee": float(r.fee)
                }
                for r in self.close_records
            ],
            "open_cost": float(self.open_cost) if hasattr(self, 'open_cost') else 0.0,
            "close_value": float(self.close_value),
            "unrealized_value": float(self.unrealized_value),
            "total_pnl": float(self.total_pnl),
            "holding_period": self.holding_period
        }

class ExposureLotAnalyzer:
    def __init__(self, db_session: Session, start_time: datetime):
        self.db = db_session
        self.start_time = start_time
        self.lots: Dict[str, List[ExposureLot]] = {} # Map "account_id|symbol" -> FIFO queue
        self.closed_lots: List[ExposureLot] = []
        
    def _get_key(self, account_id: int, symbol: str) -> str:
        return f"{account_id}|{symbol}"

    def analyze(self, end_time: datetime, account_id: Optional[int] = None) -> Dict[str, Any]:
        """
        Calculate analysis results up to end_time.
        """
        # 1. Fetch trades
        query = self.db.query(Trade).filter(Trade.trade_time >= self.start_time, Trade.trade_time <= end_time)
        if account_id:
            query = query.filter(Trade.account_id == account_id)
        
        trades = query.order_by(Trade.trade_time).all()
        
        # 2. Process trades
        for trade in trades:
            key = self._get_key(trade.account_id, trade.symbol)
            if key not in self.lots:
                self.lots[key] = []
                
            if trade.side.upper() == "BUY":
                # Create new lot
                lot = ExposureLot(
                    lot_id=f"lot_{trade.id}",
                    account_id=trade.account_id,
                    symbol=trade.symbol,
                    open_trade_id=trade.id,
                    open_time=trade.trade_time,
                    open_price=trade.price,
                    open_quantity=trade.quantity,
                    open_fee=trade.taker_fee + trade.commission, # Assuming fee is sum
                    open_interest=trade.interest_charged,
                    remaining_quantity=trade.quantity
                )
                self.lots[key].append(lot)
                
            elif trade.side.upper() == "SELL":
                # Close lots (FIFO)
                qty_to_close = trade.quantity
                
                # We need to distribute the fee proportionally to the matched quantity?
                # Or just assign fee to the records as we go?
                # Total fee for this SELL trade:
                total_sell_fee = trade.taker_fee + trade.commission
                total_sell_qty = trade.quantity
                
                while qty_to_close > 0 and self.lots[key]:
                    current_lot = self.lots[key][0]
                    
                    match_qty = min(current_lot.remaining_quantity, qty_to_close)
                    
                    # Proportional fee
                    match_fee = (match_qty / total_sell_qty) * total_sell_fee if total_sell_qty > 0 else Decimal(0)
                    
                    record = CloseRecord(
                        trade_id=trade.id,
                        time=trade.trade_time,
                        price=trade.price,
                        matched_qty=match_qty,
                        fee=match_fee
                    )
                    
                    current_lot.add_close_record(record)
                    qty_to_close -= match_qty
                    
                    if current_lot.remaining_quantity <= 0:
                        self.closed_lots.append(self.lots[key].pop(0))
                        
                # If qty_to_close > 0 but no lots left, it's an "orphan" sell or short opening?
                # Per requirement "generated by BUY", we ignore Short Open for now or log it.
                # For now, we just ignore extra sell quantity if no matching buy lot found 
                # (or maybe it means we started tracking in middle of positions).
                pass

        # 3. Finalize and Calculate PnL
        all_lots = self.closed_lots + [lot for queue in self.lots.values() for lot in queue]
        
        # Get Mark Prices for open lots
        # We need mark price for each symbol at end_time
        # Optimization: get list of symbols needed
        needed_symbols = set()
        for lot in all_lots:
            if lot.remaining_quantity > 0:
                needed_symbols.add(lot.symbol)
        
        mark_prices = self._get_mark_prices(list(needed_symbols), end_time)
        
        results = []
        for lot in all_lots:
            mark_price = mark_prices.get(lot.symbol)
            # Fallback to last close price if no mark price found?
            # Or assume 0? Using open price as fallback might be safer to avoid huge PnL swings if data missing
            if mark_price is None and lot.remaining_quantity > 0:
                # Try to find latest price
                pass 
            
            lot.calculate_metrics(mark_price, end_time)
            results.append(lot.to_dict())
            
        return {
            "start_time": self.start_time.isoformat(),
            "end_time": end_time.isoformat(),
            "lot_count": len(results),
            "lots": results
        }

    def _get_mark_prices(self, symbols: List[str], timestamp: datetime) -> Dict[str, Decimal]:
        """
        Get market prices for symbols at or near timestamp.
        """
        if not symbols:
            return {}
            
        prices = {}
        # Try CryptoKline first for more granular data
        # Find the latest kline before or at timestamp
        # This is efficient if we do it per symbol or carefully
        
        # Simple approach: Query latest price for each symbol <= timestamp
        for symbol in symbols:
            # Try CryptoKline (1m)
            kline = self.db.query(CryptoKline).filter(
                CryptoKline.symbol == symbol,
                CryptoKline.timestamp <= int(timestamp.timestamp())
            ).order_by(CryptoKline.timestamp.desc()).first()
            
            if kline:
                prices[symbol] = kline.close_price
                continue
                
            # Fallback to CryptoPrice (Daily/Snapshot)
            price_rec = self.db.query(CryptoPrice).filter(
                CryptoPrice.symbol == symbol,
                CryptoPrice.price_date <= timestamp.date()
            ).order_by(CryptoPrice.price_date.desc()).first()
            
            if price_rec:
                prices[symbol] = price_rec.price
        
        return prices

